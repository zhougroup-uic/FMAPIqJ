# PDB -> PQR helper (port of sim2iq_pre.py): radii come from per-atom mean volumes.
using JSON

const VDW = Dict("H" => 1.2, "HE" => 1.4, "LI" => 1.82, "BE" => 1.53, "B" => 1.92, "C" => 1.7,
                 "N" => 1.55, "O" => 1.52, "F" => 1.47, "NE" => 1.54, "NA" => 2.27, "MG" => 1.73,
                 "AL" => 1.84, "SI" => 2.1, "P" => 1.8, "S" => 1.8, "CL" => 1.75, "AR" => 1.88,
                 "K" => 2.75, "CA" => 2.31)

# Non-standard residue names -> standard ones used in the volume table
const RESIDUE_MAPPING = let d = Dict{String,String}(
        "HID" => "HIS", "HIE" => "HIS", "HIP" => "HIS", "HSE" => "HIS", "HSP" => "HIS", "HSC" => "HIS",
        "HSD" => "HIS", "CYX" => "CYS", "CYM" => "CYS", "CSO" => "CYS", "CSS" => "CYS", "ASH" => "ASP",
        "GLH" => "GLU", "LYN" => "LYS", "ARN" => "ARG")
    std = ["ALA", "GLY", "SER", "THR", "LEU", "ILE", "VAL", "ASN", "GLN", "ARG", "PRO", "PHE", "TRP",
           "TYR", "GLU", "ASP", "LYS", "MET", "CYS"]
    for p in ("N", "C"), r in std
        d[p*r] = r
    end
    for p in ("N", "C"), (v, r) in (("HID", "HIS"), ("HIE", "HIS"))
        d[p*v] = r
    end
    d
end

# `line[a:b]` with Python slice semantics (0-based, half-open), clamped to the line length
pyslice(s::AbstractString, a::Int, b::Int) = (n = length(s); a >= n ? "" : s[a+1:min(b, n)])

struct PDB
    pdb_lines::Vector{String}
    atomname::Vector{String}
    resname::Vector{String}
    vdw::Vector{Float64}
end

function read_pdb(filename::AbstractString)
    pdb = PDB(String[], String[], String[], Float64[])
    for line in eachline(filename)
        startswith(line, "ENDMDL") && break
        (startswith(line, "ATOM") || startswith(line, "HETA")) || continue
        push!(pdb.pdb_lines, pyslice(line, 0, 54))
        an = pyslice(strip(pyslice(line, 12, 16)), 0, 3)
        push!(pdb.atomname, an)
        push!(pdb.resname, pyslice(line, 17, 20))
        atype = "C"
        if !isempty(an) && isletter(an[1])
            atype = string(an[1])
            length(an) > 1 && isletter(an[2]) && islowercase(an[2]) && (atype *= an[2])
        end
        atype = uppercase(atype)
        dr = get(VDW, atype, get(VDW, atype[1:1], VDW["C"]))
        push!(pdb.vdw, dr)
    end
    return pdb
end

sphere_volume_from_radius(R) = 4π / 3 * R^3

# Per-atom radius from volume table, falling back to vdW radius
function unique_radii(pdb::PDB, volume_data)
    radii = Float64[]
    for i in eachindex(pdb.atomname)
        res, atm = pdb.resname[i], pdb.atomname[i]
        r = pdb.vdw[i]
        if haskey(volume_data, res) && haskey(volume_data[res], atm)
            r = sphere_radius_from_volume(volume_data[res][atm])
        elseif haskey(RESIDUE_MAPPING, res)
            m = RESIDUE_MAPPING[res]
            haskey(volume_data, m) && haskey(volume_data[m], atm) &&
                (r = sphere_radius_from_volume(volume_data[m][atm]))
        end
        push!(radii, r)
    end
    return radii
end

function write_pqr(pdb::PDB, radii, output::AbstractString)
    println("Writing PQR file to $output")
    open(output, "w") do io
        println(io, "REMARK   Generated by sim2iq_pre.py")
        println(io, "REMARK   Radii are from precomputed unique volumes")
        for i in eachindex(pdb.pdb_lines)
            @printf(io, "%s%7.4f %8.6f\n", pdb.pdb_lines[i], 0.0, radii[i])
        end
        println(io, "END")
    end
end

const DEFAULT_VOLUMES = joinpath(@__DIR__, "..", "..", "..", "data", "mean_volumes.json")

# sim2iqpre -f input.pdb [-v volumes.json] [-o output.pqr]
function sim2iqpre_main(argv::Vector{String} = copy(ARGS))
    infile = nothing; volfile = DEFAULT_VOLUMES; outfile = nothing
    i = 1
    while i <= length(argv)
        a = argv[i]
        if a in ("-f", "--file") && i < length(argv);       infile = argv[i+1]; i += 1
        elseif a in ("-v", "--volumes") && i < length(argv); volfile = argv[i+1]; i += 1
        elseif a in ("-o", "--output") && i < length(argv);  outfile = argv[i+1]; i += 1
        else
            println(stderr, "usage: sim2iqpre -f input.pdb [-v volumes.json] [-o output.pqr]"); return 2
        end
        i += 1
    end
    infile === nothing && (println(stderr, "usage: sim2iqpre -f input.pdb [-v volumes.json] [-o output.pqr]"); return 2)
    isfile(infile) || (println("Error: Input file $infile not found"); return 1)
    isfile(volfile) || (println("Error: Volume file $volfile not found"); return 1)
    outfile === nothing && (outfile = splitext(infile)[1] * "_uniqueradii.pqr")
    pdb = read_pdb(infile)
    println("Loaded PDB with $(length(pdb.pdb_lines)) atoms")
    println("Loading unique volumes from $volfile")
    radii = unique_radii(pdb, JSON.parsefile(volfile))
    write_pqr(pdb, radii, outfile)
    println("Output written to $outfile")
    return 0
end
